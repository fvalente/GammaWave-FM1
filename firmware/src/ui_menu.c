            cv_line(x1, y0 + c, x1, y1 - c, col);
            cv_line(x0, y0 + c, x0 + c, y0, col);
            cv_line(x1 - c, y0, x1, y0 + c, col);
            cv_line(x0, y1 - c, x0 + c, y1, col);
